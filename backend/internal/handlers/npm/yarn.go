package npm

import (
	"regexp"
	"strings"
)

var (
	yarnEntryHeaderRe = regexp.MustCompile(`(?m)^"?(@?[^:\s"][^:\n"]*)@([^:]+)"?:\s*$`)
	yarnVersionRe     = regexp.MustCompile(`(?m)^\s+version\s+"([^"]+)"\s*$`)
	yarnResolvedRe    = regexp.MustCompile(`(?m)^\s+resolved\s+"([^"]+)"\s*$`)
)

// LookLikeYarnLock 粗判经典 yarn.lock（v1）。
func LookLikeYarnLock(text string) bool {
	s := strings.TrimSpace(text)
	if s == "" {
		return false
	}
	if strings.HasPrefix(s, "{") {
		return false
	}
	head := s
	if len(head) > 500 {
		head = head[:500]
	}
	low := strings.ToLower(head)
	if strings.Contains(low, "lockfileversion:") || strings.Contains(low, `"lockfileversion"`) {
		return false
	}
	if strings.Contains(low, "# yarn lockfile") || strings.Contains(low, "# THIS IS AN AUTOGENERATED FILE") {
		return true
	}
	return yarnEntryHeaderRe.MatchString(s) && yarnVersionRe.MatchString(s) &&
		(strings.Contains(low, "resolved") || strings.Contains(s, `version "`))
}

// ParseYarnLock 从经典 yarn.lock 提取 tarball URL（优先 resolved，否则重建）。
func ParseYarnLock(text string) (urls []string, skipped []string) {
	seen := map[string]struct{}{}
	add := func(u string) {
		u = strings.TrimSpace(u)
		if u == "" {
			return
		}
		if i := strings.IndexByte(u, '#'); i >= 0 {
			u = u[:i]
		}
		if !strings.HasPrefix(u, "http://") && !strings.HasPrefix(u, "https://") {
			skipped = append(skipped, u)
			return
		}
		if _, ok := seen[u]; ok {
			return
		}
		seen[u] = struct{}{}
		urls = append(urls, u)
	}

	blocks := splitYarnBlocks(text)
	for _, block := range blocks {
		resolved := ""
		if m := yarnResolvedRe.FindStringSubmatch(block); m != nil {
			resolved = m[1]
		}
		if resolved != "" {
			add(resolved)
			continue
		}
		ver := ""
		if m := yarnVersionRe.FindStringSubmatch(block); m != nil {
			ver = m[1]
		}
		name := yarnNameFromHeader(block)
		if name == "" || ver == "" {
			skipped = append(skipped, strings.SplitN(block, "\n", 2)[0])
			continue
		}
		if u := ReconstructTarballURL(name, ver); u != "" {
			add(u)
		} else {
			skipped = append(skipped, name+"@"+ver)
		}
	}
	return urls, skipped
}

func splitYarnBlocks(text string) []string {
	var blocks []string
	var cur strings.Builder
	flush := func() {
		s := strings.TrimSpace(cur.String())
		if s != "" {
			blocks = append(blocks, s)
		}
		cur.Reset()
	}
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			flush()
			continue
		}
		if !strings.HasPrefix(line, " ") && !strings.HasPrefix(line, "\t") && strings.HasSuffix(strings.TrimSpace(line), ":") {
			flush()
			cur.WriteString(line)
			cur.WriteByte('\n')
			continue
		}
		if cur.Len() > 0 {
			cur.WriteString(line)
			cur.WriteByte('\n')
		}
	}
	flush()
	return blocks
}

func yarnNameFromHeader(block string) string {
	first := strings.SplitN(block, "\n", 2)[0]
	first = strings.TrimSpace(first)
	first = strings.TrimSuffix(first, ":")
	first = strings.Trim(first, `"`)
	// 可能是逗号分隔的多选择器：lodash@^4.17.21, lodash@~4.17.0
	first = strings.Split(first, ",")[0]
	first = strings.TrimSpace(first)
	first = strings.Trim(first, `"`)
	if strings.HasPrefix(first, "@") {
		// @scope/name@range
		if i := strings.LastIndex(first, "@"); i > 0 {
			return first[:i]
		}
		return ""
	}
	if i := strings.LastIndex(first, "@"); i > 0 {
		return first[:i]
	}
	return ""
}
